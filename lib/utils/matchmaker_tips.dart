  static final Random _random = Random();

  /// A random tip template, never the one currently on screen (unless there is
  /// only one). The caller resolves it for the matchmaker's gender.
  static String next({String? previous}) {
    if (tips.length == 1) {
      return tips.first;
    }
    String candidate = tips[_random.nextInt(tips.length)];
    while (candidate == previous) {
      candidate = tips[_random.nextInt(tips.length)];
    }
    return candidate;
  }
